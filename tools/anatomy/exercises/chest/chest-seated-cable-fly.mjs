// Arm path rebuilt from a simple 3-D arm: the handles travel from out to the side, forward
// and slightly up, until the hands meet in front of the upper chest. The earlier projection
// ended with both hands beside the ears and the arms hidden behind the shoulders.
const rad = Math.PI / 180, lerp = (a, b, t) => a + (b - a) * t;
const sub3 = (a, b) => a.map((v, i) => v - b[i]), add3 = (a, b) => a.map((v, i) => v + b[i]);
const mul3 = (a, k) => a.map(v => v * k), dot3 = (a, b) => a.reduce((n, v, i) => n + v * b[i], 0);
const len3 = a => Math.hypot(...a), unit3 = a => mul3(a, 1 / (len3(a) || 1));
function elbow(H, upper, fore, hint) { // shoulder at the origin
  const D = Math.min(len3(H), upper + fore - 0.001), u = unit3(H);
  const q = unit3(sub3(hint, mul3(u, dot3(hint, u))));
  const a = (upper * upper - fore * fore + D * D) / (2 * D), h = Math.sqrt(Math.max(0, upper * upper - a * a));
  return add3(mul3(u, a), mul3(q, h));
}
const angleFromDown = (x, y) => Math.atan2(x, y) / rad;
function flyArm(p, sign) {
  // x outward from the shoulder, y down, z toward the viewer.
  const theta = lerp(6, 106, p) * rad, reach = lerp(119, 106, p), drop = lerp(10, -2, p);
  const H = [Math.cos(theta) * reach, drop, Math.sin(theta) * reach];
  const E = elbow(H, 64, 59, [0.55, 0.75, 0]);
  const e = [sign * E[0], E[1]], h = [sign * H[0], H[1]], fe = [h[0] - e[0], h[1] - e[1]];
  const upperAbs = angleFromDown(e[0], e[1]), foreAbs = angleFromDown(fe[0], fe[1]);
  // [0, 360) keeps the elbow angle continuous as the forearm swings past straight-on.
  let el = sign * (foreAbs - upperAbs);
  while (el >= 360) el -= 360;
  while (el < 0) el += 360;
  return {abd: sign * upperAbs, el, f: Math.hypot(...e) / 64, ff: Math.hypot(...fe) / 59};
}
const arms = p => ({r: flyArm(p, 1), l: flyArm(p, -1)});
for (const key of spec.track.keys) spec.poses[key.pose].arms = arms(key.p);
spec.poses.start.arms = arms(0);
spec.poses.peak.arms = arms(1);
